function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[char]));
}

function escapeWordList(words) {
  return (words || []).map((word) => `<span>${escapeHtml(word)}</span>`).join("");
}

function highlightEge14Target(context, target) {
  const safeContext = escapeHtml(context);
  const safeTarget = escapeHtml(target);
  if (!safeTarget || !safeContext.includes(safeTarget)) return safeContext;
  return safeContext.replace(safeTarget, `<mark class="ege14-target">${safeTarget}</mark>`);
}

function safeRelativeUrl(value, fallback = "#") {
  const url = String(value || "").trim();
  return url.startsWith("/") && !url.startsWith("//") ? url : fallback;
}

function api(path, options = {}) {
  const headers = { "Content-Type": "application/json", ...(options.headers || {}) };
  if (state.token) headers.Authorization = `Bearer ${state.token}`;
  return fetch(path, { ...options, headers }).then(async (response) => {
    const data = await response.json();
    if (!response.ok) {
      const error = new Error(data.error || "Ошибка запроса");
      Object.assign(error, data);
      throw error;
    }
    return data;
  });
}

async function downloadRequest(path, filename, options = {}) {
  const headers = { ...(options.headers || {}) };
  if (options.body) headers["Content-Type"] = "application/json";
  if (state.token) headers.Authorization = `Bearer ${state.token}`;
  const response = await fetch(path, { ...options, headers });
  if (!response.ok) {
    const data = await response.json().catch(() => ({ error: "Ошибка скачивания" }));
    throw new Error(data.error || "Ошибка скачивания");
  }
  const blob = await response.blob();
  const disposition = response.headers.get("Content-Disposition") || "";
  const headerName = disposition.match(/filename="?([^"]+)"?/i)?.[1];
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = headerName || filename;
  link.click();
  URL.revokeObjectURL(link.href);
}

