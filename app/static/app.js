function shopMediaUrl(value) {
  const url = String(value || "").trim();
  if (!url) return "";
  if (url.startsWith("/") && !url.startsWith("//")) return encodeURI(url);
  if (/^https?:\/\//i.test(url)) return encodeURI(url);
  return "";
}

