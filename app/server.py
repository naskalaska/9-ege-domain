            """
            SELECT word_id, error_count AS errors
            FROM word_progress
            WHERE user_id = ? AND scope_id = ? AND due_reviews > 0
            ORDER BY due_reviews DESC, error_count DESC, last_seen_at DESC
            LIMIT 20
            """,
            (user_id, scope_id_for("errors")),
