    for student in students:
        user_id = student["user_id"]
        summary = con.execute(
            """
            SELECT COUNT(*) AS total, COALESCE(SUM(is_correct), 0) AS correct,
                   COUNT(DISTINCT word_id) AS touched
            FROM attempts
            WHERE user_id = ?
            """,
            (user_id,),
        ).fetchone()
